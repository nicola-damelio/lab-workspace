/* ⚠ THE DEPTH IS THE SURFACE'S, NEVER A CENTRE'S. The first version projected
   the CENTRE of every sphere and wrote that one depth over the whole disc: a
   billboard. Half of a ball then sat « behind » its own centre, so a ball
   occluded its own far edge, and the pixel's world point — which is what the
   lamp is asked about — was the middle of the atom instead of the patch of skin
   the camera really sees. Every rasterizer below writes the true point and its
   true normal, so the two passes can be compared honestly. */
export const ndcZOf = (clip, x, y, z) => {
  const cw = clip[3] * x + clip[7] * y + clip[11] * z + clip[15];
  if (!(Math.abs(cw) > 1e-9)) return 2;
  return (clip[2] * x + clip[6] * y + clip[10] * z + clip[14]) / cw;
};
const writePixel = (out, idx, z, x, y, z2, nx, ny, nz2, scale, needN) => {
  if (!(z < out.depth[idx])) return false;
  out.depth[idx] = z;
  out.hit[idx] = 1;
  if (out.world) {
    out.world[idx * 3] = x;
    out.world[idx * 3 + 1] = y;
    out.world[idx * 3 + 2] = z2;
  }
  if (needN && out.normal) {
    const l = Math.sqrt(nx * nx + ny * ny + nz2 * nz2);
    const s = l > 1e-9 ? 1 / l : 0;
    out.normal[idx * 3] = nx * s;
    out.normal[idx * 3 + 1] = ny * s;
    out.normal[idx * 3 + 2] = nz2 * s;
  }
  return true;
};
/* THE BUFFERS OF ONE PASS, ALLOCATED ONCE AND THEN SHARED. A single pass is
   built by SEVERAL rasterizers that all draw into the SAME depth map — the balls
   first, then the capsules that fill the links between them, then the REAL
   TRIANGLES (a band, a plate) — each of them keeping whatever is nearer. They are
   therefore initialised WHEN THEY ARE ALLOCATED and never cleared again: wiping
   them here would erase the balls the moment the capsules arrived.
   ⚠ The buffers must also live ON `out`, which is what `writePixel` reads: the
   first version built them locally and only published `world` / `normal`, so a
   fresh pass had `out.depth === undefined` and every ball threw on the very first
   writePixel. */
const surfaceBuffer = (out, w, h, needWorld = true, needNormal = true) => {
  const size = w * h;
  if (!out.depth || out.depth.length !== size) {
    out.depth = new Float32Array(size);
    out.depth.fill(2);
    out.hit = new Uint8Array(size);
    out.hit.fill(0);
  }
  if (needWorld && (!out.world || out.world.length !== size * 3)) out.world = new Float32Array(size * 3);
  if (needNormal && (!out.normal || out.normal.length !== size * 3)) out.normal = new Float32Array(size * 3);
  return out;
};
export const rasterizeSpheres = ({
  positions, radii, count = 0, clip, width, height,
  radiusScale = 1, right = [1, 0, 0], up = [0, 1, 0], back = [0, 0, 1],
  needNormal = true, needWorld = true,
}, out = {}) => {
  const w = Math.max(1, Math.round(width));
  const h = Math.max(1, Math.round(height));
  const n = Math.max(0, Math.min(count || Math.floor(positions.length / 3), Math.floor(positions.length / 3)));
  surfaceBuffer(out, w, h, needWorld, needNormal);
  const clipPt = new Array(4);
  const scr = new Array(3);
  const scrEdge = new Array(3);
  const maxRadius = Math.max(w, h) * 2;

  for (let i = 0; i < n; i += 1) {
    const x = positions[i * 3], y = positions[i * 3 + 1], z = positions[i * 3 + 2];
    if (!Number.isFinite(x) || !Number.isFinite(y) || !Number.isFinite(z)) continue;
    const r = Math.max(0.1, (radii ? radii[i] : 1.7) * radiusScale);
    const c = clipToScreen(mat4TransformPoint(clip, [x, y, z], clipPt), w, h, scr);
    if (!c) continue;
    let rad = 1;
    if (clipToScreen(mat4TransformPoint(clip, [
      x + up[0] * r, y + up[1] * r, z + up[2] * r,
    ], clipPt), w, h, scrEdge)) {
      const dx = scrEdge[0] - c[0], dy = scrEdge[1] - c[1];
      rad = Math.max(1, Math.min(Math.sqrt(dx * dx + dy * dy), maxRadius));
    }
    const cx = c[0], cy = c[1];
    const x0 = Math.max(0, Math.floor(cx - rad));
    const x1 = Math.min(w - 1, Math.ceil(cx + rad));
    const y0 = Math.max(0, Math.floor(cy - rad));
    const y1 = Math.min(h - 1, Math.ceil(cy + rad));
    const r2 = rad * rad;
    /* The image plane's ÅNGSTRÖM PER PIXEL at this atom: a pixel offset turns
       into the point of the sphere it really sees (the parallel-ray
       approximation: ~0.04 Å of error for a 1.7 Å ball seen from 80 Å). */
    const perPx = r / rad;

    for (let py = y0; py <= y1; py += 1) {
      const dy = py + 0.5 - cy;
      const row = py * w;
      for (let px = x0; px <= x1; px += 1) {
        const dx = px + 0.5 - cx;
        const d2 = dx * dx + dy * dy;
        if (d2 > r2) continue;
        const u = dx * perPx;
        const v = dy * perPx;
        const n2 = r * r - u * u - v * v;
        if (!(n2 > 0)) continue;
        const nd = Math.sqrt(n2);
        const wx = x + right[0] * u + up[0] * v + back[0] * nd;
        const wy = y + right[1] * u + up[1] * v + back[1] * nd;
        const wz = z + right[2] * u + up[2] * v + back[2] * nd;
        writePixel(out, row + px, ndcZOf(clip, wx, wy, wz), wx, wy, wz,
          right[0] * u + up[0] * v + back[0] * nd,
          right[1] * u + up[1] * v + back[1] * nd,
          right[2] * u + up[2] * v + back[2] * nd, r, needNormal);
      }
    }
  }
  return { ...out, width: w, height: h, count: n };
};

export const rasterizeCapsules = ({
  positions, radii, edges, clip, width, height,
  radiusScale = 1, right = [1, 0, 0], up = [0, 1, 0], back = [0, 0, 1],
  needNormal = true, needWorld = true,
}, out = {}) => {
  const w = Math.max(1, Math.round(width));
  const h = Math.max(1, Math.round(height));
  surfaceBuffer(out, w, h, needWorld, needNormal);
  if (!out.depth) return out;

  const clipPt = new Array(4);
  const scrA = new Array(3), scrB = new Array(3);
  const edgeA = new Array(3), edgeB = new Array(3);

  for (let i = 0; i + 1 < (edges ? edges.length : 0); i += 2) {
    const iA = edges[i], iB = edges[i + 1];
    const ax = positions[iA * 3], ay = positions[iA * 3 + 1], az = positions[iA * 3 + 2];
    const bx = positions[iB * 3], by = positions[iB * 3 + 1], bz = positions[iB * 3 + 2];

    const cA = clipToScreen(mat4TransformPoint(clip, [ax, ay, az], clipPt), w, h, scrA);
    const cB = clipToScreen(mat4TransformPoint(clip, [bx, by, bz], clipPt), w, h, scrB);
    if (!cA || !cB) continue;

    const rA = Math.max(0.1, radii[iA] * radiusScale);
    const rB = Math.max(0.1, radii[iB] * radiusScale);

    let pxRadA = 1, pxRadB = 1;
    if (clipToScreen(mat4TransformPoint(clip, [ax + up[0] * rA, ay + up[1] * rA, az + up[2] * rA], clipPt), w, h, edgeA)) {
      pxRadA = Math.max(1, Math.sqrt((edgeA[0] - cA[0]) ** 2 + (edgeA[1] - cA[1]) ** 2));
    }
    if (clipToScreen(mat4TransformPoint(clip, [bx + up[0] * rB, by + up[1] * rB, bz + up[2] * rB], clipPt), w, h, edgeB)) {
      pxRadB = Math.max(1, Math.sqrt((edgeB[0] - cB[0]) ** 2 + (edgeB[1] - cB[1]) ** 2));
    }

    const maxR = Math.max(pxRadA, pxRadB);
    const x0 = Math.max(0, Math.floor(Math.min(cA[0], cB[0]) - maxR));
    const x1 = Math.min(w - 1, Math.ceil(Math.max(cA[0], cB[0]) + maxR));
    const y0 = Math.max(0, Math.floor(Math.min(cA[1], cB[1]) - maxR));
    const y1 = Math.min(h - 1, Math.ceil(Math.max(cA[1], cB[1]) + maxR));

    const dx = cB[0] - cA[0];
    const dy = cB[1] - cA[1];
    const len2 = dx * dx + dy * dy;
    const perA = rA / pxRadA;
    const perB = rB / pxRadB;

    for (let py = y0; py <= y1; py += 1) {
      const row = py * w;
      const deltaY = py + 0.5 - cA[1];
      for (let px = x0; px <= x1; px += 1) {
        const deltaX = px + 0.5 - cA[0];
        let t = 0;
        if (len2 > 0) t = Math.max(0, Math.min(1, (deltaX * dx + deltaY * dy) / len2));
        const offX = deltaX - t * dx;
        const offY = deltaY - t * dy;
        const radAtT = pxRadA + t * (pxRadB - pxRadA);
        if (offX * offX + offY * offY > radAtT * radAtT) continue;
        /* THE SURFACE OF THE TUBE, not its axis (same recipe as the sphere,
           with the axis point in place of the centre): a cylinder's radial
           profile is the same at every t, and the round caps come out right
           because t is clamped to the ends. */
        const rr = rA + t * (rB - rA);
        const perPx = perA + t * (perB - perA);
        const u = offX * perPx;
        const v = offY * perPx;
        const n2 = rr * rr - u * u - v * v;
        if (!(n2 > 0)) continue;
        const nd = Math.sqrt(n2);
        const wx = ax + t * (bx - ax) + right[0] * u + up[0] * v + back[0] * nd;
        const wy = ay + t * (by - ay) + right[1] * u + up[1] * v + back[1] * nd;
        const wz = az + t * (bz - az) + right[2] * u + up[2] * v + back[2] * nd;
        writePixel(out, row + px, ndcZOf(clip, wx, wy, wz), wx, wy, wz,
          right[0] * u + up[0] * v + back[0] * nd,
          right[1] * u + up[1] * v + back[1] * nd,
          right[2] * u + up[2] * v + back[2] * nd, rr, needNormal);
      }
    }
  }
  return out;
};

/* ⚠ THE REAL TRIANGLES — the half of the method that was missing. An INDEXED
   mesh (`position` 3 floats per vertex, `normal` 3 floats per vertex, an index
   array of triples) is rasterized here the way the GPU would: the screen-area
   test picks the pixels, the NDC depth (linear in screen space — exact) picks
   the visible one, and the WORLD POINT and the normal are interpolated with the
   PERSPECTIVE-CORRECT weights (a plate seen at an angle must land where it is,
   not where a naive interpolation would put it). This is what makes a ring
   plate hide the ribbon behind it in the shape of its hexagon. */
export const rasterizeTriangles = ({
  positions, normals = null, indices, count = 0, clip, width, height, stride = 1,
  needWorld = true, needNormal = true,
}, out = {}) => {
  const w = Math.max(1, Math.round(width));
  const h = Math.max(1, Math.round(height));
  surfaceBuffer(out, w, h, needWorld, needNormal);
  if (!out.depth) return out;
  const total = Math.max(0, Math.min(
    count || Math.floor(indices.length / 3),
    Math.floor(indices.length / 3),
  ));
  const step = Math.max(1, Math.round(stride));
  const sa = new Array(3), sb = new Array(3), sc = new Array(3);
  const clipPt = new Array(4);
  let drawn = 0;

  for (let t = 0; t < total; t += step) {
    const ia = indices[t * 3] * 3, ib = indices[t * 3 + 1] * 3, ic = indices[t * 3 + 2] * 3;
    const ax = positions[ia], ay = positions[ia + 1], az = positions[ia + 2];
    const bx = positions[ib], by = positions[ib + 1], bz = positions[ib + 2];
    const cx = positions[ic], cy = positions[ic + 1], cz = positions[ic + 2];
    const wa = mat4TransformPoint(clip, [ax, ay, az], clipPt);
    const wA = wa[3];
    const pa = clipToScreen(wa, w, h, sa);
    if (!pa) continue;
    const wb = mat4TransformPoint(clip, [bx, by, bz], clipPt);
    const wB = wb[3];
    const pb = clipToScreen(wb, w, h, sb);
    if (!pb) continue;
    const wc = mat4TransformPoint(clip, [cx, cy, cz], clipPt);
    const wC = wc[3];
    const pc = clipToScreen(wc, w, h, sc);
    if (!pc) continue;

    const area = (pb[0] - pa[0]) * (pc[1] - pa[1]) - (pb[1] - pa[1]) * (pc[0] - pa[0]);
    if (!(Math.abs(area) > 1e-9)) continue;
    const inv = 1 / area;
    const x0 = Math.max(0, Math.floor(Math.min(pa[0], pb[0], pc[0])));
    const x1 = Math.min(w - 1, Math.ceil(Math.max(pa[0], pb[0], pc[0])));
    const y0 = Math.max(0, Math.floor(Math.min(pa[1], pb[1], pc[1])));
    const y1 = Math.min(h - 1, Math.ceil(Math.max(pa[1], pb[1], pc[1])));
    const kA = Math.abs(wA) > 1e-9 ? 1 / wA : 0;
    const kB = Math.abs(wB) > 1e-9 ? 1 / wB : 0;
    const kC = Math.abs(wC) > 1e-9 ? 1 / wC : 0;
    drawn += 1;

    for (let py = y0; py <= y1; py += 1) {
      const row = py * w;
      const y = py + 0.5;
      for (let px = x0; px <= x1; px += 1) {
        const x = px + 0.5;
        const l0 = ((pb[0] - x) * (pc[1] - y) - (pb[1] - y) * (pc[0] - x)) * inv;
        if (l0 < 0) continue;
        const l1 = ((pc[0] - x) * (pa[1] - y) - (pc[1] - y) * (pa[0] - x)) * inv;
        if (l1 < 0) continue;
        const l2 = 1 - l0 - l1;
        if (l2 < 0) continue;
        const idx = row + px;
        const zNdc = l0 * pa[2] + l1 * pb[2] + l2 * pc[2];
        if (!(zNdc < out.depth[idx])) continue;
        const sum = l0 * kA + l1 * kB + l2 * kC;
        const s = Math.abs(sum) > 1e-9 ? 1 / sum : 0;
        const m0 = l0 * kA * s, m1 = l1 * kB * s, m2 = l2 * kC * s;
        const wx = m0 * ax + m1 * bx + m2 * cx;
        const wy = m0 * ay + m1 * by + m2 * cy;
        const wz = m0 * az + m1 * bz + m2 * cz;
        let nx = 0, ny = 0, nz = 1;
        if (normals) {
          nx = m0 * normals[ia] + m1 * normals[ib] + m2 * normals[ic];
          ny = m0 * normals[ia + 1] + m1 * normals[ib + 1] + m2 * normals[ic + 1];
          nz = m0 * normals[ia + 2] + m1 * normals[ib + 2] + m2 * normals[ic + 2];
        }
        writePixel(out, idx, zNdc, wx, wy, wz, nx, ny, nz, 1, needNormal && !!normals);
      }
    }
  }
  return { ...out, triangles: total, drawn };
};

export const softenMask = (mask, width, height, radius) => {
  const w = Math.max(1, Math.round(width));
  const h = Math.max(1, Math.round(height));
  const r = Number(radius) || 0;
  if (!(r > 0)) return mask;
  const far = Math.max(1, Math.round(r));
  const weights = [];
  let sum = 0;
  for (let i = -far; i <= far; i += 1) {
    const k = Math.max(0, 1 - Math.abs(i) / (r + 1));
    weights.push(k);
    sum += k;
  }
  const tmp = new Float32Array(mask.length);
  const out = new Float32Array(mask.length);
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < w; x += 1) {
      let acc = 0;
      for (let i = -far; i <= far; i += 1) {
        const sx = Math.min(w - 1, Math.max(0, x + i));
        acc += mask[y * w + sx] * weights[i + far];
      }
      tmp[y * w + x] = acc / sum;
    }
  }
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < w; x += 1) {
      let acc = 0;
      for (let i = -far; i <= far; i += 1) {
        const sy = Math.min(h - 1, Math.max(0, y + i));
        acc += tmp[sy * w + x] * weights[i + far];
      }
      out[y * w + x] = acc / sum;
    }
  }
  return out;
};
export const pcfDiscOf = (taps) => {
  const n = Math.max(1, Math.round(Number(taps) || 1));
  const out = new Float32Array(n * 2);
  const golden = Math.PI * (3 - Math.sqrt(5));
  for (let i = 0; i < n; i += 1) {
    const r = n === 1 ? 0 : Math.sqrt((i + 0.5) / n);
    const a = i * golden;
    out[i * 2] = Math.cos(a) * r;
    out[i * 2 + 1] = Math.sin(a) * r;
  }
  return out;
};
export const pcfRotationOf = (x, y) => {
  const h = Math.sin(x * 12.9898 + y * 78.233) * 43758.5453;
  return (h - Math.floor(h)) * Math.PI * 2;
};
/* SELF-SHADOWING ON THE MOLECULE ITSELF — AND WHY THERE IS NONE. Every pixel the
   camera's pass covered owns a WORLD POINT and a NORMAL — the patch of skin the
   viewer really sees. That point is pushed into the lamp's frame and compared with
   what the lamp saw FIRST at that pixel. The receiver is in its own depth map, so
   it occludes itself by exactly zero and no « footprint » trick is needed to keep
   a shadow off its own edges — that trick, plus a wide « ambient » blur of the
   mask, is what made the first version dirty the molecule.
   What is written is the OCCLUSION WEIGHTED BY THE LAMP'S SHARE:
   `occlusion · (floor + (1 − floor)·|N·L|)`. A face fully under the lamp keeps
   all of the shadow, a face the lamp grazes keeps a little (so the shadow
   stays legible on a ribbon's side wall), a face the lamp never lights keeps
   only the floor — and the mask is ZERO outside the receiver's own coverage, so
   the background is never touched. */
export const shadowMaskOf = ({
  camera, light, lightDir = [0, 0, 1], width, height, biasNdc = 0, softness = 0,
  taps = 1, penumbra = 0, penumbraMax = 0, depthScale = 0, facingFloor = 0,
}) => {
  const w = Math.max(1, Math.round(width));
  const h = Math.max(1, Math.round(height));
  const mask = new Float32Array(w * h);
  const base = Math.max(0, Number(softness) || 0);
  const grow = Math.max(0, Number(penumbra) || 0);
  const cap = Math.max(0, Number(penumbraMax) || 0);
  const perAngstrom = Number(depthScale) > 0 ? 1 / Number(depthScale) : 0;
  const normals = camera.normal || null;
  const floor = Math.min(1, Math.max(0, Number(facingFloor) || 0));
  const L = normalize3(lightDir);
  const discCache = new Map();
  const discOf = (n) => {
    let d = discCache.get(n);
    if (!d) { d = pcfDiscOf(n); discCache.set(n, d); }
    return d;
  };
  const discTaps = Math.max(1, Math.round(Number(taps) || 1));
  const clipX = (x) => Math.min(w - 1, Math.max(0, x));
  const clipY = (y) => Math.min(h - 1, Math.max(0, y));
  const clipPt = new Array(4);
  const scr = new Array(3);
  let shadowed = 0, penumbraRadius = 0, maxTaps = 0, facingSum = 0, facingCount = 0;
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < w; x += 1) {
      const idx = y * w + x;
      if (!camera.hit[idx]) continue;
      const p = clipToScreen(mat4TransformPoint(light.clip, [
        camera.world[idx * 3], camera.world[idx * 3 + 1], camera.world[idx * 3 + 2],
      ], clipPt), w, h, scr);
      if (!p) continue;
      const lx = clipX(Math.floor(p[0]));
      const ly = clipY(Math.floor(p[1]));
      const nearest = light.depth[ly * w + lx];
      /* ⚠ THE CENTRE RAY IS NOT A GATE. A penumbra is precisely the case where the
         centre ray MISSES the occluder while the rays around it hit it: skipping
         the pixel here would erase the whole soft edge — and with it the shadow of
         anything thinner than the disc. The DISC decides; the centre ray only
         measures the GAP that PCSS grows the disc by. */
      const gap = nearest < 2 ? p[2] - nearest : 0;
      /* THE DISC IS THE SOFTNESS, PLUS WHAT THE GAP ADDS (PCSS). A soft edge is a
         WIDTH the user chose; the depth gap between the receiver and the occluder
         only pushes the disc further (PCSS: a contact shadow stays crisp while a
         cast shadow spreads). `blur: 0` therefore gives the hard step of a plain
         shadow map — the radius is 0 and the centre ray decides. */
      const radius = Math.min(cap > 0 ? cap : Infinity,
        base + (grow > 0 && gap > biasNdc ? grow * gap * perAngstrom : 0));
      let occluded = 0;
      if (radius > 0) {
        if (radius > penumbraRadius) penumbraRadius = radius;
        const need = Math.min(SHADOW_MAX_TAPS, Math.max(discTaps, Math.ceil(radius * SHADOW_TAPS_PER_PIXEL)));
        const disc = discOf(need);
        const invTaps = 1 / need;
        if (need > maxTaps) maxTaps = need;
        const rot = pcfRotationOf(x, y);
        const cs = Math.cos(rot), sn = Math.sin(rot);
        for (let t = 0; t < disc.length; t += 2) {
          const ox = disc[t] * radius, oy = disc[t + 1] * radius;
          const sx = clipX(Math.round(lx + ox * cs - oy * sn));
          const sy = clipY(Math.round(ly + ox * sn + oy * cs));
          const d = light.depth[sy * w + sx];
          if (d < 2 && p[2] > d + biasNdc) occluded += invTaps;
        }
      } else {
        if (!(gap > biasNdc)) continue;
        occluded = 1;
      }
      if (!(occluded > 0)) continue;
      let face = 1;
      if (normals) {
        const nx = normals[idx * 3], ny = normals[idx * 3 + 1], nz = normals[idx * 3 + 2];
        face = Math.abs(nx * L[0] + ny * L[1] + nz * L[2]);
        facingSum += face;
        facingCount += 1;
      }
      mask[idx] = occluded * (floor + (1 - floor) * face);
      if (occluded >= 0.5) shadowed += 1;
    }
  }
  /* ⚠ LA COUVERTURE EST UNE FRONTIÈRE, PAS UN DÉCOR. `softenMask` étale le trait de
     quelques pixels ; hors du dessin, ces pixels n'ont AUCUN point du monde, et le
     masque y multiplierait un fond blanc — le liseré sombre du rapport, mesuré :
     3 538 pixels de fond assombris sur une scène réelle. Le masque est donc ramené
     à ZÉRO partout où la passe caméra n'a rien vu : une ombre n'existe que SUR une
     surface, jamais à côté. */
  const softened = softenMask(mask, w, h, base);
  if (base > 0) {
    for (let i = 0; i < softened.length; i += 1) {
      if (!camera.hit[i]) softened[i] = 0;
    }
  }
  return {
    mask: softened, width: w, height: h, shadowed,
    taps: discTaps, tapsMax: maxTaps, penumbraRadius,
    facing: {
      floor,
      mean: facingCount ? facingSum / facingCount : 1,
      sampled: facingCount,
    },
  };
};
export const sampleMaskBilinear = (mask, mw, mh, nx, ny) => {
  const width = Math.max(1, Math.round(mw));
  const height = Math.max(1, Math.round(mh));
  const mx = Math.min(width - 1, Math.max(0, nx * width - 0.5));
  const my = Math.min(height - 1, Math.max(0, ny * height - 0.5));
  const x0 = Math.floor(mx), y0 = Math.floor(my);
  const x1 = Math.min(width - 1, x0 + 1), y1 = Math.min(height - 1, y0 + 1);
  const fx = mx - x0, fy = my - y0;
  const a = mask[y0 * width + x0], b = mask[y0 * width + x1];
  const c = mask[y1 * width + x0], d = mask[y1 * width + x1];
  return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy;
};
export const applyShadowToPixels = (data, width, height, mask, maskWidth, maskHeight, strength) => {
  const s = Math.min(1, Math.max(0, Number(strength) || 0));
  if (!(s > 0) || !data || !mask) return 0;
  const w = Math.max(1, Math.round(width));
  const h = Math.max(1, Math.round(height));
  let touched = 0;
  for (let y = 0; y < h; y += 1) {
    const ny = (y + 0.5) / h;
    for (let x = 0; x < w; x += 1) {
      const m = sampleMaskBilinear(mask, maskWidth, maskHeight, (x + 0.5) / w, ny);
      if (!(m > 0.002)) continue;
      const f = 1 - s * m;
      const i = (y * w + x) * 4;
      const r = Math.round(data[i] * f);
      const g = Math.round(data[i + 1] * f);
      const b = Math.round(data[i + 2] * f);
      if (r === data[i] && g === data[i + 1] && b === data[i + 2]) continue;
      data[i] = r; data[i + 1] = g; data[i + 2] = b;
      touched += 1;
    }
  }
  return touched;
};

