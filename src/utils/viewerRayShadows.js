export const proxyRadiusOf = (rep, vdwRadius = 1.7, el = null) => {
  const stroke = PROXY_STROKE_BY_TYPE[repTypeOf(rep, el)];
  if (!stroke) return null;
  const vdw = Math.max(0.1, Number(vdwRadius) || 1.7);
  const radiusScale = repNumber(rep, el, 'radiusScale', 'sphereScale', 'scale');
  const radiusSize = repNumber(rep, el, 'radiusSize', 'radius');
  const aspect = repNumber(rep, el, 'aspectRatio');
  const radiusType = String((rep && rep.radiusType) || '').toLowerCase();
  const sizeType = radiusType === '' || radiusType === 'size';
  const core = (fallback) => {
    if (radiusSize > 0 && (sizeType || radiusScale <= 0)) return radiusSize;
    if (radiusScale > 0) return vdw * radiusScale;
    return fallback;
  };
  let r;
  switch (stroke.kind) {
    case 'vdw': r = core(vdw); break;
    case 'ball': r = core(stroke.core) * (aspect || stroke.aspect); break;
    case 'bond': r = core(stroke.core); break;
    case 'spline':
      r = radiusScale > 0 ? stroke.base * (radiusScale / stroke.scale) : stroke.base;
      if (radiusSize > 0 && sizeType) r = Math.max(r, radiusSize);
      break;
    case 'tube':
      r = sizeType && radiusSize > 0 ? radiusSize : (radiusScale > 0 ? stroke.base * radiusScale : stroke.base);
      break;
    default: r = stroke.min;
  }
  return Math.max(0.05, Math.max(stroke.min, r));
};
const atomProxyOf = (structure) => {
  try {
    if (!structure || typeof structure.getAtomProxy !== 'function') return null;
    const ap = structure.getAtomProxy();
    return ap && typeof ap.isBackbone === 'function' ? ap : null;
  } catch { return null; }
};
const drawsBackboneOf = (ap, idx) => {
  if (!ap) return false;
  try {
    for (let i = 0; i < idx.length; i += 1) {
      const a = idx[i];
      if (!(a >= 0)) continue;
      ap.index = a;
      if (ap.isBackbone()) return true;
    }
  } catch { return false; }
  return false;
};
/* ⚠ A STROKE OWNS ONLY WHAT IT DRAWS — « spheric shadows for bonds » was the
   report, and on the picture the round balls fell exactly on the CYCLES and on the
   BRANCHES of the side chains. The cause: NGL's Tube of the backbone and the
   Licorice of the side chains SHARE ONE SELECTION, and `StructureView#getAtomIndices`
   returns the WHOLE list of that selection, side chains included. A « chain » kind
   (BACKBONE_ONLY_KINDS — spline / tube) therefore answers for the backbone atoms
   only, asking the very question NGL asks itself (`AtomProxy#isBackbone()` →
   `residueType.backboneIndexList`, the list the cartoon and the tube build their
   geometry from): the other atoms of the list it shares with the sticks are drawn by the sticks,
   at THEIR own stroke. */
export const drawnProxyRadiiOf = (comp, atomCount, vdw = null, links = null, splines = null, covered = null) => {
  const list = comp && comp.reprList;
  if (!Array.isArray(list)) return null;
  const out = new Float32Array(Math.max(0, Math.round(Number(atomCount) || 0)));
  if (!out.length) return out;
  out.fill(NaN);
  const ap = atomProxyOf(comp && comp.structure);
  list.forEach((el) => {
    try {
      const rep = (el && (el.repr || el)) || null;
      if (!rep || rep.visible === false) return;
      /* ⚠ A REPRESENTATION WHOSE REAL TRIANGLES WERE READ NEEDS NO PROXY. The
         triangles ARE the drawn shape (see worldTrianglesOf) — a ball at an atom or
         a capsule along a link would only ADD a rim the drawing does not have.
         Measured in Chrome: without this, the 0.45 Å balls of a cartoon put 1 756
         fully shadowed pixels on the white background, up to 6 px from the ribbon.
         The proxy stays for the case it was made for: a draw whose geometry cannot
         be read yet (a build still in NGL's queue). */
      if (covered && covered.has(el)) return;
      const op = opacityOf(rep, el);
      if (op <= INVISIBLE_OPACITY) return;
      const sv = rep.structureView;
      if (!sv || typeof sv.getAtomIndices !== 'function') return;
      const idx = sv.getAtomIndices();
      if (!idx || !idx.length) return;
      const kind = repKindOf(rep, el);
      const linked = LINKED_KINDS[kind] === 1;
      const chainOnly = BACKBONE_ONLY_KINDS[kind] === 1 && drawsBackboneOf(ap, idx);
      for (let i = 0; i < idx.length; i += 1) {
        const a = idx[i];
        if (!(a >= 0 && a < out.length)) continue;
        if (chainOnly) {
          ap.index = a;
          if (!ap.isBackbone()) continue;    // the spline does not draw here
          /* ⚠ A SPLINE RUNS THROUGH THE *TRACE* ATOMS, NOT THROUGH THE BACKBONE
             BLOCK. A cartoon is a surface built on the trace (the CA of a protein,
             `residue.traceAtomIndex`); a ball on the N or the C sits ~1.2 Å off that
             path and therefore OUTSIDE the drawn ribbon. Measured on a real NGL
             stage in Chrome: those balls put 1 335 fully shadowed pixels on the
             white background, up to 2 Å away from the ribbon — the « dirt » of the
             report. Only the trace atom is the drawn shape of a spline, and it is
             the only one the trace chain below links. */
          if (!(ap.residue && ap.residue.traceAtomIndex === a)) continue;
          if (splines) splines[a] = 1;
        }
        const per = proxyRadiusOf(rep, vdw ? vdw[a] : 1.7, el);
        if (per == null) continue;
        const seen = op < 1 ? per * op : per;
        if (!(out[a] >= seen)) out[a] = seen;
        /* A SPLINE DOES NOT DRAW BONDS: its links are its own chain (see
           drawnBondsOf), so it never marks an atom as a stick's endpoint. */
        if (linked && links && !chainOnly) links[a] = 1;
      }
    } catch { }
  });
  return out;
};
export const opacityOf = (rep, el = null) => {
  const sources = [rep, el && el.parameters, rep && rep.parameters];
  for (let s = 0; s < sources.length; s += 1) {
    const source = sources[s];
    if (!source) continue;
    const v = Number(source.opacity);
    if (Number.isFinite(v)) return Math.min(1, Math.max(0, v));
  }
  return 1;
};
/* A COMPACT VIEW OF ONE ATTRIBUTE. NGL does interleave some buffers; a reader
   that assumes `array[i * 3]` while the buffer really holds `array[i * stride +
   offset]` silently reads another attribute's numbers — which is precisely how
   the first version invented a band direction out of positions. Anything
   interleaved is therefore copied out, once, into a plain array. */
export const compactAttribute = (attr, itemSize) => {
  if (!attr || !attr.array) return null;
  const a = attr.array;
  const data = attr.data;
  if (!data || data.stride === itemSize) return { array: a, count: attr.count, stride: itemSize };
  const stride = data.stride;
  const offset = attr.offset || 0;
  const count = Math.min(attr.count, Math.max(0, Math.floor((a.length - offset) / stride)));
  const out = new Float32Array(count * itemSize);
  for (let i = 0; i < count; i += 1) {
    const base = i * stride + offset;
    for (let c = 0; c < itemSize; c += 1) out[i * itemSize + c] = a[base + c];
  }
  return { array: out, count, stride: itemSize };
};
/* ⚠ WHICH BUFFERS ARE SURFACES, AND WHICH ARE IMPOSTORS. Measured on NGL 2.4
   in a real browser: an INDEXED mesh of a drawn surface (cartoon, ribbon, tube,
   rope, surface, and the ring plates of « Stylized rings ») carries a `normal`
   attribute; an impostor (a ball, a stick, a wire, a point) carries none — its
   shape is cut out in the FRAGMENT shader from `radius` / `position1` /
   `position2`, and its vertices are the corners of a quad. So the presence of
   normals IS the discriminator: a geometry without them is never read as
   triangles, whatever its representation is called. */
export const trianglesOfGeometry = (geometry, type = '') => {
  if (!geometry || !geometry.attributes) return null;
  if (IMPOSTOR_TYPES[String(type).toLowerCase()]) return null;
  const idx = geometry.index;
  if (!idx || !idx.array || idx.array.length < 3) return null;
  const pos = compactAttribute(geometry.attributes.position, 3);
  const nor = compactAttribute(geometry.attributes.normal, 3);
  if (!pos || !pos.array || !nor || !nor.array) return null;
  if (pos.array.length < 9) return null;
  const count = Math.floor(idx.array.length / 3);
  return {
    type: String(type || '').toLowerCase(),
    positions: pos.array,
    normals: nor.array,
    indices: idx.array,
    count: Math.max(0, count),
  };
};

/* THE REAL TRIANGLES OF ONE COMPONENT, IN WORLD SPACE. Every visible
   representation contributes the indexed meshes it really draws — and so do the
   RING PLATES, whether they are reached through the representation's bufferList
   (`addBufferRepresentation` puts the MeshBuffer there) or through the
   `__plates` mark the viewer leaves on the element. Nothing is re-derived from
   the atoms: the hexagon of a base is the hexagon that was drawn. */
export const worldTrianglesOf = (comp, viewerM = null) => {
  const empty = {
    positions: new Float32Array(0), normals: new Float32Array(0), indices: new Uint32Array(0),
    count: 0, vertexCount: 0, reps: 0, plates: 0, kinds: '', debug: '', surfaces: [],
  };
  const list = comp && comp.reprList;
  if (!Array.isArray(list)) return { ...empty, debug: 'no reprList' };
  const own = elements16Of(comp.matrix);
  const m = own
    ? (viewerM ? mat4Multiply(viewerM, own) : own)
    : elements16Of(comp.group && comp.group.matrixWorld);
  const chunks = [];
  const seen = new Set();
  const kinds = [];
  const surfaces = [];
  let total = 0, plates = 0, found = 0, debug = '';
  const takeGeometry = (geometry, type, isPlate) => {
    if (!geometry || seen.has(geometry)) return;
    seen.add(geometry);
    const tri = trianglesOfGeometry(geometry, type);
    if (!tri || !tri.count) return;
    chunks.push({ tri, isPlate });
    total += tri.count;
    if (isPlate) plates += 1;
  };
  list.forEach((el) => {
    try {
      const rep = (el && (el.repr || el)) || null;
      if (!rep || rep.visible === false) return;
      if (opacityOf(rep, el) <= INVISIBLE_OPACITY) return;
      const type = repTypeOf(rep, el);
      const mark = el && el.__plates && el.__plates.mesh && el.__plates.mesh.geometry;
      const before = total;
      /* ⚠ TWO PLACES, AND BOTH ARE REAL. `StructureRepresentation#attach` copies
         what `create()` built in `dataList` into `bufferList` and hands it to the
         viewer (measured in the installed build), so an ATTACHED representation
         holds its meshes in `bufferList` — but one whose build is still queued
         (a still asked right after a load) holds them in `dataList` ONLY, and a
         reader that knew just one of the two would silently cast nothing. Reading
         both, deduplicating by geometry, is the same set of triangles either way. */
      const chunks = Array.isArray(rep.bufferList) ? rep.bufferList.slice() : [];
      if (Array.isArray(rep.dataList)) {
        rep.dataList.forEach((data) => {
          if (data && Array.isArray(data.bufferList)) data.bufferList.forEach((b) => chunks.push(b));
        });
      }
      chunks.forEach((b) => { if (b && b.geometry) takeGeometry(b.geometry, type, !!mark && b.geometry === mark); });
      if (mark) takeGeometry(mark, type, true);
      if (total > before) {
        found += 1;
        surfaces.push(el);
        if (type && !kinds.includes(type)) kinds.push(type);
      }
    } catch (e) { if (!debug) debug = `error: ${e.message}`; }
  });
  if (!total) return { ...empty, debug: debug || 'no triangle mesh drawn' };
  let vertexCount = 0;
  chunks.forEach(({ tri }) => { vertexCount += Math.floor(tri.positions.length / 3); });
  const positions = new Float32Array(vertexCount * 3);
  const normals = new Float32Array(vertexCount * 3);
  const indices = new Uint32Array(total * 3);
  let at = 0, it = 0;
  chunks.forEach(({ tri }) => {
    const p = tri.positions, nn = tri.normals, ix = tri.indices;
    const n = Math.min(Math.floor(p.length / 3), Math.floor(nn.length / 3));
    for (let i = 0; i < n; i += 1) {
      const x = p[i * 3], y = p[i * 3 + 1], z = p[i * 3 + 2];
      const nx = nn[i * 3], ny = nn[i * 3 + 1], nz = nn[i * 3 + 2];
      if (m) {
        positions[at * 3] = m[0] * x + m[4] * y + m[8] * z + m[12];
        positions[at * 3 + 1] = m[1] * x + m[5] * y + m[9] * z + m[13];
        positions[at * 3 + 2] = m[2] * x + m[6] * y + m[10] * z + m[14];
        normals[at * 3] = m[0] * nx + m[4] * ny + m[8] * nz;
        normals[at * 3 + 1] = m[1] * nx + m[5] * ny + m[9] * nz;
        normals[at * 3 + 2] = m[2] * nx + m[6] * ny + m[10] * nz;
      } else {
        positions[at * 3] = x; positions[at * 3 + 1] = y; positions[at * 3 + 2] = z;
        normals[at * 3] = nx; normals[at * 3 + 1] = ny; normals[at * 3 + 2] = nz;
      }
      at += 1;
    }
    for (let t = 0; t < tri.count * 3; t += 1) {
      const vi = ix[t];
      indices[it] = at - n + (vi < n ? vi : 0);
      it += 1;
    }
  });
  return {
    positions, normals, indices,
    count: total, vertexCount: at, reps: found, plates,
    kinds: kinds.join('·'), debug: '', surfaces,
  };
};
export const emptyTriangles = () => ({
  positions: new Float32Array(0), normals: new Float32Array(0), indices: new Uint32Array(0),
  count: 0, vertexCount: 0, reps: 0, plates: 0, kinds: '', debug: '',
});

/* THE ATOM PROXIES, AS ONE SET OF BALLS AND CAPSULES. (The old version also
   merged a « band brush » in here; the bands are REAL TRIANGLES now — see
   `fillTriangles` below — so nothing is re-derived from the atoms any more.)
   `count` is the number of BALLS — one per drawn atom — and `filled` the number
   of CAPSULES that join them along a real bond: the two halves of a stroke's
   shadow, both drawn by `rasterizeCapsules` in each pass. */
const fillDrawnLinks = (parts, stride, maxAtoms) => {
  const layouts = parts.filter((part) => part.data && part.data.position).map((part) => layOut(part, stride));
  const slots = layouts.reduce((a, lay) => a + lay.len, 0);
  const capacity = Math.max(1, Math.min(slots, maxAtoms || slots));
  const out = new Float32Array(capacity * 3);
  const radii = new Float32Array(capacity);

  const totalEdges = layouts.reduce((a, lay) => a + (lay.edges ? lay.edges.length : 0), 0);
  const edges = new Int32Array(totalEdges);
  let edgeK = 0;

  let k = 0;
  layouts.forEach((lay) => {
    const startK = k;
    for (let e = 0; e < lay.len && k < capacity; e += 1) {
      out[k * 3] = lay.wpos[e * 3];
      out[k * 3 + 1] = lay.wpos[e * 3 + 1];
      out[k * 3 + 2] = lay.wpos[e * 3 + 2];
      radii[k] = lay.wrad[e];
      k += 1;
    }
    if (lay.edges) {
      for (let p = 0; p < lay.edges.length; p += 1) {
        edges[edgeK++] = lay.edges[p] + startK;
      }
    }
  });
  return { positions: out, radii, count: k, edges, filled: Math.floor(edges.length / 2) };
};
/* THE TRIANGLES OF THE WHOLE SCENE, merged and budgeted. One accumulator for
   every component; `stride` thins the list when a system is huge (the same
   bargain as `maxAtoms` for the balls) instead of silently dropping the
   geometry of a whole molecule. */
const fillTriangles = (parts, maxTriangles) => {
  const total = parts.reduce((a, part) => a + (part.tris ? part.tris.count : 0), 0);
  if (!total) return { ...emptyTriangles(), stride: 1, total: 0 };
  const cap = Math.max(1, Math.round(Number(maxTriangles) || total));
  const stride = total > cap ? Math.ceil(total / cap) : 1;
  const drawn = Math.ceil(total / stride);
  const vertexCount = parts.reduce((a, part) => a + (part.tris ? part.tris.vertexCount : 0), 0);
  const positions = new Float32Array(vertexCount * 3);
  const normals = new Float32Array(vertexCount * 3);
  const indices = new Uint32Array(drawn * 3);
  let at = 0, it = 0, kept = 0, plates = 0, reps = 0;
  const kinds = [];
  parts.forEach((part) => {
    const tri = part.tris;
    if (!tri || !tri.count) return;
    reps += tri.reps;
    plates += tri.plates;
    if (tri.kinds) tri.kinds.split('·').forEach((k) => { if (k && !kinds.includes(k)) kinds.push(k); });
    const base = at;
    positions.set(tri.positions, at * 3);
    normals.set(tri.normals, at * 3);
    at += tri.vertexCount;
    for (let t = 0; t < tri.count; t += stride) {
      if (kept >= drawn) break;
      indices[it] = tri.indices[t * 3] + base;
      indices[it + 1] = tri.indices[t * 3 + 1] + base;
      indices[it + 2] = tri.indices[t * 3 + 2] + base;
      it += 3;
      kept += 1;
    }
  });
  return {
    positions, normals, indices,
    count: kept, vertexCount: at, reps, plates,
    kinds: kinds.join('·'), debug: '', stride, total,
  };
};

/* THE GRAPH OF LINKS BETWEEN THE DRAWN ATOMS. It is read from the STRUCTURE
   (`eachBond` → `atomIndex1` / `atomIndex2`, which NGL builds from the residue
   templates AND from the peptide bond it checks by distance) and never invented
   out of "the next atom of the list": that list is the whole selection, so the
   atom after a backbone oxygen is a side-chain carbon, and filling it drew the
   ghost disc of the report.
   A pair is a link only when BOTH its atoms are drawn by a stroke, and only when
   it is a BOND — closer than LINK_MAX (a residue template can join two CAs two
   residues apart, and a stroke drawn across the molecule is a link no eye sees).
   A stroke drawn without its links alone leaves holes ångströms wide that no ray can hit
   — measured: 0 shadowed pixels on 3655, against 3160 on 12247 once the links are
   filled — and THAT is the graph of the structure that is followed here
   (`eachBond`), never « the next atom of the list », which filled ghost bonds.
   When the structure declares no graph at all, the only fallback is the polymer
   TRACE (the trace atom of CONSECUTIVE residues), which is where a ribbon's
   continuity actually lives. */
const drawnBondsOf = (structure, links, n, positions = null, splines = null) => {
  if (!structure || typeof structure.eachBond !== 'function') return [];
  const out = [];
  const seen = new Set();
  const isBond = (a, b) => {
    if (!positions) return true;
    const dx = positions[a * 3] - positions[b * 3];
    const dy = positions[a * 3 + 1] - positions[b * 3 + 1];
    const dz = positions[a * 3 + 2] - positions[b * 3 + 2];
    return dx * dx + dy * dy + dz * dz <= LINK_MAX * LINK_MAX;
  };
  const addBond = (a, b) => {
    if (!(a >= 0 && a < n && b >= 0 && b < n) || a === b) return;
    if (links[a] !== 1 || links[b] !== 1) return;
    if (!isBond(a, b)) return;
    const key = a < b ? a * n + b : b * n + a;
    if (seen.has(key)) return;
    seen.add(key);
    out.push(a, b);
  };
  let linked = false;
  for (let i = 0; i < n && !linked; i += 1) linked = links[i] === 1;
  if (linked) {
    try {
      structure.eachBond((bond) => { addBond(bond.atomIndex1, bond.atomIndex2); });
    } catch { }
    if (out.length === 0) {
      try {
        if (typeof structure.eachPolymer === 'function') {
          structure.eachPolymer((p) => {
            let prevTrace = -1;
            p.eachResidue((r) => {
              const trace = r.traceAtomIndex;
              if (trace !== undefined && trace >= 0) {
                if (prevTrace >= 0) addBond(prevTrace, trace);
                prevTrace = trace;
              }
            });
          });
        }
      } catch { }
    }
  }
  /* AND THE SPLINE'S OWN CHAIN, ALWAYS — a cartoon/ribbon/tube draws a CONTINUOUS
     surface along the trace atoms, so those atoms are linked to each other whether
     or not the structure's bond graph happens to join them (it joins C(i) to N(i+1),
     two atoms the ribbon does not pass through). `splines` is the mark
     `drawnProxyRadiiOf` leaves on the atoms a spline really draws. */
  let anySpline = false;
  if (splines) {
    for (let i = 0; i < n && !anySpline; i += 1) anySpline = splines[i] === 1;
  }
  if (anySpline) {
    const addTrace = (a, b) => {
      if (!(splines[a] === 1 && splines[b] === 1)) return;
      if (!isBond(a, b)) return;
      const key = a < b ? a * n + b : b * n + a;
      if (seen.has(key)) return;
      seen.add(key);
      out.push(a, b);
    };
    /* ⚠ ON MARCHE LES CHAÎNES, PAS LES POLYMÈRES. `eachPolymer` ne rend un polymère
       que pour un enchaînement RÉEL de résidus (mesuré : RIEN pour un dipeptide dont
       les coordonnées ne font pas une liaison peptidique parfaite), alors qu'un ruban
       se dessine sur n'importe quelle chaîne de résidus. La marche est donc faite
       chaîne par chaîne — un changement de chaîne ROMPT le trait — et la trace d'un
       résidu sans atome de trace le rompt aussi. */
    const linkChain = (traces) => {
      let prev = -1;
      traces.forEach((trace) => {
        if (trace === undefined || trace < 0) { prev = -1; return; }
        if (prev >= 0) addTrace(prev, trace);
        prev = trace;
      });
    };
    try {
      const chains = [];
      if (typeof structure.eachChain === 'function') {
        structure.eachChain((chain) => {
          const traces = [];
          if (chain && typeof chain.eachResidue === 'function') {
            chain.eachResidue((r) => traces.push(r.traceAtomIndex));
          }
          chains.push(traces);
        });
      }
      if (!chains.length && typeof structure.eachResidue === 'function') {
        const traces = [];
        structure.eachResidue((r) => traces.push(r.traceAtomIndex));
        chains.push(traces);
      }
      chains.forEach(linkChain);
    } catch { }
  }
  return out;
};

const layOut = (part, stride) => {
  const slotOf = new Map();
  const own = elements16Of(part.comp.matrix);
  const m = own
    ? (part.viewerM ? mat4Multiply(part.viewerM, own) : own)
    : elements16Of(part.comp.group && part.comp.group.matrixWorld);
  const pos = part.data.position, rad = part.data.radius;
  const surface = part.surface, links = part.links;
  let measurable = false;
  if (surface) {
    for (let i = 0; i < surface.length && !measurable; i += 1) {
      measurable = Number.isFinite(surface[i]) && surface[i] > 0;
    }
  }
  const count = part.drawn ? part.drawn.length : part.n;
  const len = Math.max(0, Math.ceil(count / stride));
  const wpos = new Float32Array(Math.max(1, len) * 3);
  const wrad = new Float32Array(Math.max(1, len));
  const wlink = new Uint8Array(Math.max(1, len));
  let e = 0;
  for (let c = 0; c < count && e < len; c += stride) {
    const i = part.drawn ? part.drawn[c] : c;
    if (!(i >= 0 && i < part.n)) continue;
    const x = pos[i * 3], y = pos[i * 3 + 1], z = pos[i * 3 + 2];
    if (m) {
      wpos[e * 3] = m[0] * x + m[4] * y + m[8] * z + m[12];
      wpos[e * 3 + 1] = m[1] * x + m[5] * y + m[9] * z + m[13];
      wpos[e * 3 + 2] = m[2] * x + m[6] * y + m[10] * z + m[14];
    } else {
      wpos[e * 3] = x; wpos[e * 3 + 1] = y; wpos[e * 3 + 2] = z;
    }
    const vdw = rad && Number.isFinite(rad[i]) ? rad[i] : 1.7;
    const stroke = surface ? surface[i] : NaN;
    if (surface && measurable && !(Number.isFinite(stroke) && stroke > 0)) continue;
    const drawn = Number.isFinite(stroke) && stroke > 0;
    wrad[e] = drawn ? stroke : vdw;
    wlink[e] = drawn && links && links[i] === 1 ? 1 : 0;
    slotOf.set(i, e);
    e += 1;
  }
  const maxPairs = part.bonds ? part.bonds.length / 2 : 0;
  const edges = new Int32Array(Math.max(0, maxPairs) * 2);
  let p = 0;
  if (part.bonds) {
    for (let b = 0; b + 1 < part.bonds.length; b += 2) {
      const sa = slotOf.get(part.bonds[b]);
      const sb = slotOf.get(part.bonds[b + 1]);
      if (sa === undefined || sb === undefined) continue;
      edges[p] = sa; edges[p + 1] = sb;
      p += 2;
    }
  }
  return {
    wpos, wrad, wlink, len: e,
    edges: p === edges.length ? edges : edges.subarray(0, p),
  };
};

export const atomsFromStage = (stage, maxAtoms = RAY_SHADOW_DEFAULTS.maxAtoms, maxTriangles = RAY_SHADOW_DEFAULTS.maxTriangles) => {
  const comps = (stage && stage.compList) || [];
  const viewerM = viewerMatrixOf(stage);
  const parts = [];
  let total = 0;
  comps.forEach((comp) => {
    try {
      if (!comp || comp.visible === false) return;
      const tris = worldTrianglesOf(comp, viewerM);
      const structure = comp.structure;
      if (!structure || typeof structure.getAtomData !== 'function') {
        if (tris.count) parts.push({ comp, tris, n: 0 });
        return;
      }
      const data = structure.getAtomData({ what: { position: true, radius: true } });
      if (!data || !data.position || !data.position.length) {
        if (tris.count) parts.push({ comp, tris, n: 0 });
        return;
      }
      const n = Math.floor(data.position.length / 3);
      if (!n) return;
      const drawn = drawnAtomIndicesOf(comp, structure.atomCount || n);
      if (drawn && !drawn.length) return;
      const links = new Uint8Array(n);
      const splines = new Uint8Array(n);
      const surface = drawnProxyRadiiOf(comp, n, data.radius, links, splines, new Set(tris.surfaces || []));
      const bonds = drawnBondsOf(structure, links, n, data.position, splines);
      parts.push({ comp, data, n, drawn, surface, links, viewerM, bonds, tris });
      total += drawn ? drawn.length : n;
    } catch { }
  });
  const stride = total > maxAtoms ? Math.ceil(total / maxAtoms) : 1;
  return {
    ...fillDrawnLinks(parts, stride, maxAtoms),
    tris: fillTriangles(parts, maxTriangles),
    stride,
    total,
  };
};
export const cameraFromViewer = (viewer) => {
  const cam = (viewer && (viewer.camera || viewer.perspectiveCamera || viewer.orthographicCamera)) || null;
  const viewOffset = cam && cam.view;
  if (viewOffset && viewOffset.enabled === true) {
    throw new Error('the camera is inside a tile of a ✨ Ray still (setViewOffset) — read it before the render');
  }
  const proj = cam ? elements16Of(cam.projectionMatrix) : null;
  const view = cam ? elements16Of(cam.matrixWorldInverse) : null;
  if (!proj || !view) throw new Error('the viewer has no camera to cast a shadow from');
  return { projection: proj, view, clip: mat4Multiply(proj, view), type: (cam && cam.type) || 'Camera' };
};
export const rayShadowInputsOf = (stage, { lightDir = [0, 0, 1], options = {} } = {}) => {
  const o = rayShadowOptions(options);
  const viewer = stage && stage.viewer;
  const atoms = atomsFromStage(stage, o.maxAtoms, o.maxTriangles);
  const tris = atoms.tris || emptyTriangles();
  if (!atoms.count && !tris.count) throw new Error('nothing to cast a shadow from');
  const camera = cameraFromViewer(viewer);
  /* THE FRAME HOLDS EVERYTHING THAT CASTS OR RECEIVES: the balls (WIDENED BY THEIR
     OWN RADII — a solid reaches past its centre, see expandBoxOf) and the real
     triangles (a band or a plate can stick out of the atoms' box). */
  const boxA = atoms.count
    ? expandBoxOf(boundsBoxOf(atoms.positions, atoms.count), maxStrokeRadiusOf(atoms) * o.sphereScale)
    : null;
  const boxB = tris.count ? boundsBoxOf(tris.positions, tris.vertexCount) : null;
  const bounds = unionBoxOf(boxA, boxB);
  const center = [
    (bounds.min[0] + bounds.max[0]) / 2,
    (bounds.min[1] + bounds.max[1]) / 2,
    (bounds.min[2] + bounds.max[2]) / 2,
  ];
  const radius = Math.max(1e-3, 0.5 * Math.sqrt(
    (bounds.max[0] - bounds.min[0]) ** 2
    + (bounds.max[1] - bounds.min[1]) ** 2
    + (bounds.max[2] - bounds.min[2]) ** 2,
  ));
  const dir = normalize3(lightDir);
  const distance = radius * 100;
  const light = {
    dir, center, radius, distance, bounds,
    ...shadowRigOf({ dir, bounds, center, radius, distance, margin: o.fitMargin }),
  };
  return { atoms, camera, light, options: o };
};

