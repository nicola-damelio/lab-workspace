/* =========================================================================
src/utils/viewerRayShadows.js
CAST SHADOWS for the « ✨ Ray » still.

THE METHOD, AND WHY IT CHANGED (the report: « the shadows generated by ray are
ugly, they dirty the molecule, and the aromatic rings do not project their
hexagons on the surrounding ribbons »).

The first version rebuilt an APPROXIMATION of the scene out of the atoms (a
ball per atom, a capsule per bond, and — for a band — a brush of small balls
re-derived from the geometry's sections) and multiplied the result into every
pixel of the still. Measured against NGL 2.4 in a real browser (Chrome,
SwiftShader), three of its premises were simply false:

  1. THE BAND WAS NEVER READ. NGL's cartoon geometry is an INDEXED TRIANGLE
     MESH — `position` is 3 floats per vertex (2430 floats for 810 vertices)
     with a `normal` attribute and a 4728-index Uint16Array. The old reader
     assumed a stride of 12 floats per vertex, so `2430 % 12 !== 0` made
     `bandSectionsOf` return null: a CARTOON CAST NOTHING AT ALL (only the
     atoms' balls did), which is the « flat, detached smudge » of the reports.
     On a ribbon (936 floats — a multiple of 12 by accident) the reader mixed
     up position / dir / size at the wrong stride and built a brush pointing in
     a made-up direction: the ugly blobs.

  2. THE AROMATIC PLATES WERE INVISIBLE. The filled hexagons of « Stylized
     rings » are `MeshBuffer`s handed to the component with
     `addBufferRepresentation`; they live in `comp.reprList` with
     `rep.type === 'buffer'` and NO `structureView`. The old reader only looked
     at representation TYPES it knew (`FLAT_STROKE_BY_TYPE.cartoon` /
     `.ribbon`), so a base's hexagon was neither an occluder nor a receiver:
     no hexagon could ever land on the ribbon behind it.

  3. THE COMPOSITE DIRTIED EVERYTHING. `applyShadowToPixels` multiplied every
     pixel where the mask was > 0.002 — background included — and the mask was
     inflated twice: the receiver's OWN footprint was added to the PCF disc of
     every pixel (so each stroke self-shadowed along its edges), and a wide
     « ambient » blur of the mask was blended in at 0.85 over a 4 Å radius (so
     a dark smear spread over the molecule and past its silhouette). Nothing
     knew the surface's normal, so a face turned AWAY from the lamp was
     darkened by the same amount as a lit one.

THE METHOD NOW. Nothing is rebuilt and nothing is guessed: the same geometry
NGL draws is rasterized here, twice, in the two frames that matter.

  · THE OCCLUDERS AND THE RECEIVERS are the DRAWN SHAPES, in three kinds:
      — a SPHERE per atom and a CAPSULE per bond, ANALYTIC (NGL draws those as
        screen-space impostors — verified: their buffers carry `radius`,
        `position1`/`position2` and NO normal — so a sphere/capsule of the
        given radius IS the drawn shape, per pixel, exactly);
      — the REAL TRIANGLES of every buffer that carries a `normal` attribute:
        cartoon · ribbon · tube · rope · surface · and the RING PLATES (the
        hexagons), which is what makes an aromatic ring project its hexagon.
        The frame of the stills is read from the geometry itself, never from a
        table of representation types: a buffer with normals is a surface, a
        buffer without them is an impostor (balls, sticks, lines).
  · TWO PASSES: the camera's (it stores, per pixel, the WORLD POINT of the
    visible surface and its WORLD NORMAL — no depth is needed to compare, the
    point itself is the truth) and the lamp's (the same shapes, orthographic,
    keeping the NDC depth of those same surface points).
  · THE TEST is the honest one: the receiver's own world point is projected
    into the lamp and compared with what the lamp saw FIRST at that pixel. The
    receiver is in its own depth map, so it occludes itself by exactly zero —
    no footprint trick, no bias keeping a fake self-shadow alive.
  · THE DARKNESS IS THE LAMP'S SHARE. A pixel is darkened by
    `1 − strength · occlusion · w(normal)`, where `w` falls with the angle
    between the surface and the lamp (a face the lamp does not light has no
    light to remove) and never goes below `facingFloor` so the shadow stays
    legible on a ribbon's side walls. The mask is ZERO outside the receiver's
    own coverage, so the background — and every pixel the molecule does not
    own — is never touched. That is what stops the « dirt ».

WHAT A SHADOW CANNOT DO IN NGL 2.4. The interactive canvas has NO shadow pass at
all (verified in the installed build: no shadow map, no SSAO — only an unused
three.js AO-map chunk that nothing binds), so a ✨ Ray still is the ONLY place a
cast shadow can exist in this viewer. It is computed here and multiplied into the
pixels NGL has just written, after the fact: the scene itself is never touched.

======================================================================== */
