/**
 * Renders a professional outline icon.
 * @param {string}  name  icon name or an emoji (auto-mapped)
 * @param {number}  size  rendered size in px
 * @param {string}  className
 * @param {number}  strokeWidth
 */
export const Icon = ({ name, size = 18, className = '', strokeWidth = 1.8 }) => {
  const key = (name && EMOJI_MAP[name]) || name;
  const node = paths[key];
  if (!node) {
    // Unknown name — keep the original glyph so nothing disappears.
    return <span className={className} style={{ fontSize: size, lineHeight: 1 }}>{name}</span>;
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {node}
    </svg>
  );
};

export default Icon;

