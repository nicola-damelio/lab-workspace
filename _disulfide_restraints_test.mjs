/* =========================================================================
   _disulfide_restraints_test.mjs — ⚭ LES PONTS DISULFURE → DES DISTANCES, ET LA
   RENUMÉROTATION QUI VA JUSQU'AU BOUT DU PANNEAU 🧬.

   Deux demandes de cette session, et ce qui doit rester vrai :

     ① « the constraints generated by the button “secondary structure → phi, psi”
        do not take into account the sequence renumbering » (et, du même défaut,
        « the structure calculation … does not seem to take into account distance
        restraints ») : le numéro ÉCRIT par le panneau — la colonne `residue` des
        φ/ψ comme le libellé d'une ligne de distance — est LE NUMÉRO QUE L'ÉCRAN
        MONTRE (`displayResno`, la règle du 🔢 du viewer, la même partout
        ailleurs), et la RELECTURE d'un texte d'atome accepte ce numéro-là
        D'ABORD, puis le numéro d'origine — un fichier de distances écrit avant la
        renumérotation doit continuer de se relire, et une frappe qui dit ce que
        l'écran affiche doit trouver son atome (sinon la ligne reste « pas prête »,
        la table ne donne rien au calcul, et le ▶ Run croit qu'on ne lui a imposé
        aucune distance) ;

     ② « Can you add a button “generate distances from disulfide” which generates
        distance restraints according to the disulfide definition in the
        sequence? » : le bouton ⚭ du panneau 🧬 lit `cysDisulfides` (des POSITIONS
        DE SÉQUENCE — la définition de « Cysteine states »), les apparie à la
        molécule à l'écran par le numéro d'ORIGINE (position + `residueOffset`) et
        écrit UNE LIGNE ORDINAIRE par pont, à SS_BOND_LENGTH (2.05 Å). Une ligne
        déjà présente n'est ni doublée ni réécrite, et une paire dont les deux Sγ
        ne sont pas sur la molécule est DITE (`missing`), jamais inventée.

     ③ « the distance constraints generated by the disulfide button does not consider
        the renumbering of the sequence » : les deux CASES d'une ligne générée par le
        ⚭ écrivent le numéro MONTRÉ (la règle de `calcAtomLabel`), et les phrases qui
        nomment une paire introuvable suivent, elles aussi, la règle d'affichage de
        l'appelant (`shownResno`) — l'appariement, lui, ne bouge pas : il reste sur le
        numéro d'origine, donc les atomes conduits sont les mêmes.

   Le module pur est importé et EXÉCUTÉ ; les .jsx sont vérifiés sur le TEXTE,
   comme _disulfide_fold_test.mjs.

   Run: node _disulfide_restraints_test.mjs
   ========================================================================= */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import {
  disulfidePairsOf, disulfideRestraintsOf, DISULFIDE_RESTRAINT_TARGET,
} from './src/utils/disulfideRestraints.js';
import { SG_ATOM_NAME } from './src/utils/disulfideBonds.js';
import { SS_BOND_LENGTH } from './src/utils/disulfideFold.js';
import { originalResidueNumber } from './src/utils/residueNumbering.js';

let passed = 0;
const ok = (cond, what) => {
  assert.ok(cond, what);
  passed += 1;
};
const eq = (a, b, what) => {
  assert.deepEqual(a, b, `${what}\n  attendu : ${JSON.stringify(b)}\n  obtenu  : ${JSON.stringify(a)}`);
  passed += 1;
};
const has = (src, needle, what) => {
  assert.ok(src.includes(needle), `${what}\n  cherche : ${needle}`);
  passed += 1;
};
const read = (p) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const VIEW = read('src/components/NMRMoleculeViewer.jsx');
const NMR = read('src/components/NMRSections.jsx');
const MD = read('src/components/MDSections.jsx');
const DOCK = read('src/components/DockingSections.jsx');

/* UNE MOLÉCULE DE LABORATOIRE — un squelette minimal (N · CA · C par résidu) et un
   Sγ là où on le met. Les atomes sont ceux que le viewer lit
   (`structureAtomRecords` : index, name, resname, resno, element), et le numéro
   d'origine suit la règle de l'application (position + décalage). */
const peptide = (sgPositions, offset = 0, total = 12) => {
  const atoms = [];
  let index = 0;
  for (let pos = 1; pos <= total; pos += 1) {
    const resno = originalResidueNumber(pos - 1, offset);
    ['N', 'CA', 'C'].forEach((name) => {
      atoms.push({ index, name, resname: 'ALA', resno, element: name });
      index += 1;
    });
    if (sgPositions.includes(pos)) {
      atoms.push({ index, name: 'SG', resname: 'CYS', resno, element: 'S' });
      index += 1;
    }
  }
  return atoms;
};
const sgOf = (atoms, resno) => atoms.find((a) => a.name === 'SG' && a.resno === resno).index;

/* ── ① LES PAIRES DÉCLARÉES, NORMALISÉES ───────────────────────────────────── */
eq(disulfidePairsOf([[8, 3]]).pairs, [[3, 8]], 'une paire est rangée (la plus petite position d’abord)');
eq(disulfidePairsOf([[3, 8], [8, 3]]).pairs, [[3, 8]], 'la même paire déclarée deux fois est UN pont');
eq(disulfidePairsOf([[3, 8], [8, 3], [7, 7], [0, 4], ['x', 2]]), { pairs: [[3, 8]], dropped: 4 },
  'ce qui n’est pas deux positions entières ≥ 1 et différentes est ÉCARTÉ, et compté');
eq(disulfidePairsOf(null), { pairs: [], dropped: 0 }, 'aucune définition → aucune paire (jamais une erreur)');
eq(disulfidePairsOf([[5, 9], [1, 2]]).pairs, [[1, 2], [5, 9]], 'les paires sortent TRIÉES (indices croissants)');

/* ── ② LA CONVERSION, SANS DÉCALAGE ────────────────────────────────────────── */
const plain = peptide([3, 8]);
const plainRead = disulfideRestraintsOf({ pairs: [[3, 8]], atoms: plain });
eq(plainRead.ok, true, 'deux Cys déclarées et présentes sur la molécule → la conversion passe');
eq(plainRead.reason, 'ok', '…et la raison le dit');
eq(plainRead.declared, 1, 'une paire déclarée');
eq(plainRead.rows.length, 1, 'une ligne écrite');
eq(plainRead.rows[0].target, SS_BOND_LENGTH, 'la cible est la longueur de la liaison S–S');
eq(plainRead.rows[0].target, DISULFIDE_RESTRAINT_TARGET, '…par la constante du module (2.05 Å)');
eq(plainRead.rows[0].residue, [3, 8], 'les deux résidus d’ORIGINE de la paire');
eq(plainRead.rows[0].resname, ['CYS', 'CYS'], '…avec leur nom (le libellé de la ligne en a besoin)');
eq(plainRead.rows[0].name, ['SG', 'SG'], '…et le nom des deux atomes');
eq(plainRead.rows[0].i, sgOf(plain, 3), 'l’atome A est le SG du premier résidu');
eq(plainRead.rows[0].j, sgOf(plain, 8), 'l’atome B est le SG du second');
eq(plainRead.missing, [], 'rien ne manque');
eq(plainRead.residueOffset, 0, 'le décalage lu est celui de l’appel (0 ici)');
eq(SG_ATOM_NAME, 'SG', 'le nom d’atome cherché est celui de la règle ⚭ (une seule définition)');

/* ── ③ LA MÊME DÉFINITION SUR UNE STRUCTURE DÉCALÉE (residueOffset) ─────────
   « Sequence and structure » numérote la SÉQUENCE, la structure chargée porte son
   propre numéro : c'est `residueOffset` qui les relie (la règle unique de
   utils/residueNumbering.js). La paire [3, 8] de la séquence tombe donc sur les
   résidus 28 et 33 d'une structure qui commence à 26. */
const shifted = peptide([3, 8], 25);
const shiftedRead = disulfideRestraintsOf({ pairs: [[3, 8]], atoms: shifted, residueOffset: 25 });
eq(shiftedRead.rows.length, 1, 'une paire de la séquence se convertit sur une structure DÉCALÉE');
eq(shiftedRead.rows[0].residue, [28, 33], 'les résidus visés sont position + décalage (3+25, 8+25)');
eq(shiftedRead.rows[0].i, sgOf(shifted, 28), 'l’atome A est le SG du résidu 28');
eq(shiftedRead.rows[0].j, sgOf(shifted, 33), 'l’atome B est le SG du résidu 33');
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: shifted, residueOffset: '25' }).rows.length, 1,
  'un décalage écrit en TEXTE est lu comme un nombre');
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: shifted, residueOffset: 'x' }).reason, 'no-atom',
  'un décalage illisible retombe sur 0 (jamais NaN) : les résidus 3 et 8 sont cherchés, et ne sont pas là');

/* ── ④ CE QUI NE DONNE PAS DE LIGNE EST DIT, ET RIEN N'EST INVENTÉ ──────────── */
const lonely = disulfideRestraintsOf({ pairs: [[3, 8]], atoms: peptide([3]) });
eq(lonely.ok, false, 'un des deux Sγ manque → aucune ligne');
eq(lonely.reason, 'no-atom', '…la raison le dit');
eq(lonely.rows, [], '…rien n’est écrit');
eq(lonely.missing.length, 1, '…et la paire est NOMMÉE dans `missing`');
ok(lonely.missing[0].say.includes('residues 3 and 8'),
  '…avec les deux résidus qu’elle cherchait');
eq(disulfideRestraintsOf({ pairs: [], atoms: plain }).reason, 'no-pair',
  'aucune paire déclarée → rien à convertir (et le bouton le dit)');
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: plain, target: 2.5 }).rows[0].target, 2.5,
  'la cible peut être donnée (le défaut reste la liaison S–S)');
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: plain, target: 0 }).rows[0].target, SS_BOND_LENGTH,
  'une cible illisible retombe sur la liaison S–S');
/* Un atome sans index utilisable ne peut pas être posé dans une ligne : il est
   écarté comme les autres (le module ne devine pas un indice). */
const noIndex = plain.map((a) => (a.name === 'SG' && a.resno === 8 ? { ...a, index: null } : a));
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: noIndex }).rows.length, 0,
  'un Sγ sans index d’atome ne donne pas de ligne');
/* Les atomes peuvent arriver avec `atomname` (le nom de NGL) au lieu de `name`. */
const viaAtomname = plain.map((a) => ({ ...a, atomname: a.name, name: undefined }));
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: viaAtomname }).rows.length, 1,
  'le nom d’atome est lu dans `name` COMME dans `atomname`');
/* Plusieurs ponts : les lignes sortent dans l’ordre des indices (l’ordre de la
   table, comme les lignes piquées). */
const many = disulfideRestraintsOf({ pairs: [[8, 3], [1, 10]], atoms: peptide([1, 3, 8, 10]) });
eq(many.rows.length, 2, 'deux ponts déclarés → deux lignes');
ok(many.rows[0].i < many.rows[1].i, '…rangées par indice croissant');
eq(many.rows.map((r) => r.residue), [[1, 10], [3, 8]],
  '…et chacune sait ses deux résidus (la paire du résidu 1 vient en premier)');

/* ── ⑤ LA RENUMÉROTATION ATTEINT LE PANNEAU 🧬 (LES DEUX SENS) ───────────────
   Ce qui doit rester vrai, en clair : le numéro ÉCRIT est celui de l'écran, et le
   numéro d'ORIGINE reste LU. Les deux listes ne sont jamais fondues — une
   renumérotation peut faire coïncider le montré d'un résidu avec l'origine d'un
   autre, et une fusion fabriquerait une ambiguïté qui n'existe pas à l'écran. */
has(VIEW, 'const calcAtomLabel = (rec) => `${rec.resname || \'\'} ${rec.resno == null ? \'\' : displayResno(rec.resno)} ${rec.name || \'\'}`.trim();',
  'le libellé d’un atome écrit le numéro MONTRÉ (la règle du 🔢, celle de toute la page)');
has(VIEW, 'const shown = hitsWith((r) => displayResno(r.resno));',
  'la frappe cherche d’abord le numéro affiché à l’écran');
has(VIEW, 'const hits = shown.length ? shown : hitsWith((r) => r.resno);',
  '⚠ …et le numéro d’ORIGINE seulement s’il n’a rien trouvé (les fichiers d’avant se relisent)');
has(VIEW, 'const keysOf = (r, no) => [', 'la clé de recherche d’un atome est écrite UNE fois');
has(VIEW, '${rec.resno != null ? ` ${displayResno(rec.resno)}` : \'\'}',
  'la colonne « residue » de la table des φ/ψ dit le résidu RENUMÉROTÉ (la demande ①)');
has(VIEW, 'const calcResidueLabelOf = (index) => {',
  '…par le lecteur de résidu qui existait déjà (rien n’a été recopié)');
eq(VIEW.includes('CALC_KEY(`${r.resname}${r.resno}${r.name}`) === want'), false,
  '⚠ l’ancienne comparaison à UN seul numéro a disparu (c’était elle qui ignorait la renumérotation)');
has(VIEW, 'restraints: calcRestraintTermsOf(list),',
  'les distances de la table entrent bien dans les quatre gestes (le ▶ Run, ici)');

/* ── ⑥ LE BOUTON ⚭, ET CE QU'IL POSE DANS LA TABLE ────────────────────────── */
has(VIEW, 'import { disulfidePairsOf, disulfideRestraintsOf } from \'../utils/disulfideRestraints\';',
  'le viewer branche le module pur (il ne recopie pas la conversion)');
has(VIEW, 'cysDisulfides = [],', 'le viewer REÇOIT les ponts déclarés par la page');
has(VIEW, 'const calcConvertDisulfides = () => {', 'le geste du bouton ⚭ existe');
has(VIEW, 'onClick={calcConvertDisulfides}', '…et un bouton le déclenche');
has(VIEW, '⚭ Disulfides → distances', '…sous le nom demandé');
has(VIEW, 'disabled={!disulfidePairsOf(cysDisulfides).pairs.length}',
  '…et il est éteint quand la séquence ne déclare aucun pont (rien à convertir)');
has(VIEW, 'pairs: declared, atoms: structureAtomRecords(now.structure), residueOffset,',
  'la conversion reçoit les atomes de la molécule À L’ÉCRAN et le décalage de la condition');
has(VIEW, 'if (existing.has(key)) return;', 'un pont déjà dans la table n’est pas doublé');
has(VIEW, 'label: `${a}–${b}`,', 'le libellé de la ligne suit la règle d’affichage du viewer');
has(VIEW, 'weight: 1, w: \'1\', say: \'\', sayA: \'\', sayB: \'\',',
  'la ligne naît complète (poids 1 écrit, comme une ligne piquée)');
has(VIEW, 'A bridge needs BOTH Sγ on the molecule on screen',
  'une paire que la molécule ne porte pas est DITE, jamais inventée');
eq(VIEW.indexOf('onClick={calcConvertDisulfides}') > VIEW.indexOf('onClick={calcConvertSecondaryStructure}'),
  true, 'le bouton ⚭ est posé À CÔTÉ du ⛓ (le pont et la peinture se convertissent au même endroit)');

/* ── ⑦ LES TROIS PAGES ENVOIENT LEUR DÉFINITION ────────────────────────────── */
has(NMR, 'cysDisulfides={activeTest.cysDisulfides}', 'la page NMR envoie « Cysteine states » au viewer');
has(MD, 'cysDisulfides={activeTest.cysDisulfides}', 'la page MD aussi (même viewer, même panneau 🧬)');
has(DOCK, 'cysDisulfides={activeTest.cysDisulfides}', 'la page Docking aussi');

/* ── ⑧ LA RENUMÉROTATION VA JUSQU'AUX LIGNES GÉNÉRÉES ────────────────────────
   Le retour de cette session, mot pour mot : « the distance constraints generated
   by the disulfide button does not consider the renumbering of the sequence. »
   Ce qui a été corrigé, et ce qui doit rester vrai :

     • le texte ÉCRIT dans les deux cases d'une ligne générée suit la MÊME règle que
       le reste du panneau (`calcAtomLabel` → `displayResno`, la table du 🔢) : ce que
       le bouton pose dit donc ce que l'écran dit, comme une ligne tapée ;
     • l'APPARIEMENT, lui, ne bouge pas : il reste sur le numéro d'ORIGINE (position +
       décalage), le seul que la structure porte — les INDICES d'atomes de la ligne
       (`i`/`j`) sont donc les bons, renumérotation ou pas ;
     • une paire que la molécule ne porte pas est nommée avec le numéro de l'ÉCRAN
       quand l'appelant a donné sa règle (`shownResno`), et le résidu d'origine reste
       dans `missing[].residue` — le module ne devine rien, il applique une règle. */
const shownSay = disulfideRestraintsOf({
  pairs: [[3, 8]], atoms: peptide([3]), shownResno: (n) => n + 100,
});
eq(shownSay.missing[0].say.includes('residues 103 and 108'), true,
  'une paire introuvable est nommée avec la règle d’affichage de l’appelant');
eq(shownSay.missing[0].residue, [3, 8], '…mais la paire reste, dans `missing`, celle des résidus d’ORIGINE');
eq(shownSay.missing[0].pair, [3, 8], '…et la position de séquence est toujours là (les deux numéros sont lisibles)');
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: peptide([3]) }).missing[0].say.includes('residues 3 and 8'), true,
  'sans règle d’affichage, le module dit le numéro d’origine (rien n’a changé pour lui)');
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: peptide([3]), shownResno: 'x' }).missing[0].say
  .includes('residues 3 and 8'), true,
  'une règle d’affichage qui n’est pas une fonction est simplement absente (jamais un blanc)');
eq(disulfideRestraintsOf({ pairs: [[3, 8]], atoms: peptide([3]), shownResno: () => '' }).missing[0].say
  .includes('residues 3 and 8'), true,
  '…et une règle qui ne sait pas dire un numéro retombe sur l’origine');
const shownRows = disulfideRestraintsOf({ pairs: [[3, 8]], atoms: plain, shownResno: (n) => n + 100 });
eq(shownRows.rows[0].residue, [3, 8], 'la règle d’affichage ne touche PAS l’appariement des lignes');
eq(shownRows.rows[0].i, sgOf(plain, 3), '…ni les indices d’atomes : c’est le numéro d’ORIGINE qui les trouve');

has(VIEW, 'shownResno: displayResno,',
  'le viewer DONNE sa règle d’affichage au module (il ne la lui fait pas deviner)');
has(VIEW, 'const atomTextOf = (i) => `${row.resname[i]} ${displayResno(row.residue[i])} ${row.name[i]}`.trim();',
  '⚠ les deux cases de la ligne générée écrivent le numéro MONTRÉ (le défaut de cette session)');
has(VIEW, 'a, b, la: a, lb: b,',
  '…et ce sont ces deux textes-là qui entrent dans la table (case A, case B, les deux libellés)');
eq(VIEW.includes('const textOf = (i) => `${row.resname[i]} ${row.residue[i]} ${row.name[i]}`.trim();'), false,
  '⚠ le texte d’ORIGINE n’est plus écrit dans les cases (c’était lui qui ignorait la renumérotation)');
eq(VIEW.includes('a: textOf(0), b: textOf(1),'), false, '…et il n’en reste aucune trace dans la ligne posée');
has(VIEW, 'if (v == null || v === \'\') return resno;',
  '⚠ une case 🔢 VIDÉE restaure le numéro d’origine (sinon la ligne dirait « CYS  SG »)');
has(VIEW, 'const n = Number(v);\n  return Number.isFinite(n) ? n : resno;',
  '…et un numéro donné en TEXTE (une sauvegarde relue) est lu comme un nombre');

console.log(`_disulfide_restraints_test.mjs — ${passed} assertions OK`);


